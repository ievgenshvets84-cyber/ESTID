    fun translateSentencePattern(rawEx: String, nativeLangCode: String, wordTranslation: String): String? {
        val w = wordTranslation.split(" / ").firstOrNull()?.trim() ?: wordTranslation.trim()

        // 1. "It is important to ... regularly."
        if (rawEx.startsWith("It is important to ") && rawEx.endsWith(" regularly.")) {
            return when (nativeLangCode) {
                "de" -> "Es ist wichtig, regelmäßig ${w} zu üben."
                "en" -> "It is important to ${w} regularly."
                "es" -> "Es importante ${w} con regularidad."
                "fr" -> "Il est important de ${w} régulièrement."
                "it" -> "È importante ${w} regolarmente."
                "pt" -> "É importante ${w} com regularidade."
                "ru" -> "Важно регулярно ${w}."
                "uk" -> "Важливо регулярно ${w}."
                "zh" -> "经常${w}是很重要的。"
                "ja" -> "定期的に${w}することが重要です。"
                "ko" -> "정기적으로 ${w}하는 것이 중요합니다."
                else -> rawEx
            }
        }

        // 2. "It is important to ... every day." / "It is fundamental to ... every day."
        if ((rawEx.startsWith("It is important to ") || rawEx.startsWith("It is fundamental to ")) && rawEx.endsWith(" every day.")) {
            return when (nativeLangCode) {
                "de" -> "Es ist wichtig, jeden Tag ${w} zu praktizieren."
                "en" -> "It is important to ${w} every day."
                "es" -> "Es importante ${w} todos los días."
                "fr" -> "Il est important de ${w} tous les jours."
                "it" -> "È importante ${w} ogni giorno."
                "pt" -> "É importante ${w} todos os dias."
                "ru" -> "Важно ${w} каждый день."
                "uk" -> "Важливо ${w} щодня."
                "zh" -> "每天${w}是很重要的。"
                "ja" -> "毎日${w}することが大切です。"
                "ko" -> "매일 ${w}하는 것이 중요합니다."
                else -> rawEx
            }
        }

        // 3. "We would gladly like to ... ."
        if (rawEx.startsWith("We would gladly like to ")) {
            return when (nativeLangCode) {
                "de" -> "Wir möchten gerne ${w}."
                "en" -> "We would gladly like to ${w}."
                "es" -> "Nos gustaría mucho ${w}."
                "fr" -> "Nous aimerions beaucoup ${w}."
                "it" -> "Vorremmo molto ${w}."
                "pt" -> "Gostaríamos muito de ${w}."
                "ru" -> "Мы с радостью хотели бы ${w}."
                "uk" -> "Ми з радістю хотіли б ${w}."
                "zh" -> "我们很乐意去${w}。"
                "ja" -> "喜んで${w}したいです。"
                "ko" -> "기꺼이 ${w}하고 싶습니다."
                else -> rawEx
            }
        }

        // 4. "... plays an essential role."
        if (rawEx.endsWith(" plays an essential role.")) {
            return when (nativeLangCode) {
                "de" -> "${w} spielt eine wesentliche Rolle."
                "en" -> "${w} plays an essential role."
                "es" -> "${w} juega un papel esencial."
                "fr" -> "${w} joue un rôle essentiel."
                "it" -> "${w} gioca un ruolo essenziale."
                "pt" -> "${w} desempenha um papel essencial."
                "ru" -> "${w} играет существенную роль."
                "uk" -> "${w} відіграє істотну роль."
                "zh" -> "${w}起着至关重要的作用。"
                "ja" -> "${w}は重要な役割を果たします。"
                "ko" -> "${w}은(는) 필수적인 역할을 합니다."
                else -> rawEx
            }
        }

        // 5. "It is essential to ... regularly."
        if (rawEx.startsWith("It is essential to ") && rawEx.endsWith(" regularly.")) {
            return when (nativeLangCode) {
                "de" -> "Es ist unerlässlich, regelmäßig ${w} zu praktizieren."
                "en" -> "It is essential to ${w} regularly."
                "es" -> "Es esencial ${w} con regularidad."
                "fr" -> "Il est essentiel de ${w} régulièrement."
                "it" -> "È essenziale ${w} regolarmente."
                "pt" -> "É essencial ${w} regularmente."
                "ru" -> "Необходимо регулярно ${w}."
                "uk" -> "Необхідно регулярно ${w}."
                "zh" -> "经常${w}是必不可少的。"
                "ja" -> "定期的に${w}することが不可欠です。"
                "ko" -> "정기적으로 ${w}하는 것이 필수적입니다."
                else -> rawEx
            }
        }

        // 6. "This experience brings a lot of ... ." / "This experience brings great ... ."
